-- weather_embeddings.sql
-- Table to store text chunk embeddings for semantic search using pgvector
-- Requires: CREATE EXTENSION vector;

-- Enable pgvector extension (run this first)
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS weather_embeddings (
    -- Primary key
    id BIGSERIAL PRIMARY KEY,
    
    -- Foreign key to weather_documents
    document_id TEXT NOT NULL,
    
    -- Chunk information
    chunk_index INTEGER NOT NULL,     -- Position of chunk in document (0-based)
    chunk_text TEXT NOT NULL,         -- The actual text chunk (800 chars with 100 overlap)
    
    -- Vector embedding (384 dimensions for all-MiniLM-L6-v2)
    embedding vector(384) NOT NULL,   -- pgvector type
    
    -- Metadata
    model_name TEXT DEFAULT 'sentence-transformers/all-MiniLM-L6-v2',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    -- Foreign key constraint
    CONSTRAINT fk_document 
        FOREIGN KEY (document_id) 
        REFERENCES weather_documents(id) 
        ON DELETE CASCADE,
    
    -- Unique constraint to prevent duplicate chunks
    CONSTRAINT unique_document_chunk 
        UNIQUE (document_id, chunk_index)
);

-- HNSW index for fast approximate nearest neighbor search
-- Using cosine distance (<=>) operator
CREATE INDEX IF NOT EXISTS idx_weather_embeddings_hnsw 
    ON weather_embeddings 
    USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);

