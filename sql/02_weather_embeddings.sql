-- Index on document_id for joining back to source documents
CREATE INDEX IF NOT EXISTS idx_weather_embeddings_document_id 
    ON weather_embeddings(document_id);

-- Index on created_at for time-based queries
CREATE INDEX IF NOT EXISTS idx_weather_embeddings_created_at 
    ON weather_embeddings(created_at DESC);

-- Comments for documentation
COMMENT ON TABLE weather_embeddings IS 
    'Stores vector embeddings of weather document text chunks for semantic search';

COMMENT ON COLUMN weather_embeddings.embedding IS 
    'Vector embedding (384-dim) generated by sentence-transformers/all-MiniLM-L6-v2';

COMMENT ON COLUMN weather_embeddings.chunk_text IS 
    'Text chunk (max 800 chars with 100 char overlap between chunks)';

COMMENT ON INDEX idx_weather_embeddings_hnsw IS 
    'HNSW index for fast cosine similarity search on embeddings';

